# STATION PROCESSING
# ============================================================

def process_station(station_name, url):
    """
    Scrape one station's playlist, enrich with Deezer info,
    write to CSV and add new songs to YouTube.
    """

    print(f"\n=== Processing {station_name} ===")

    log_path = os.path.join(
        OUTPUT_DIR,
        f"{station_name}_log.txt"
    )

    os.makedirs(
        OUTPUT_DIR,
        exist_ok=True
    )

    with open(
        log_path,
        "a",
        encoding="utf-8"
    ) as log:

        log.write(
            f"Script started (daily) for {station_name}\n"
        )

    # --------------------------------------------------------
    # Authenticate with YouTube
    # --------------------------------------------------------

    try:
        youtube = get_youtube_service()

        print(
            "Successfully authenticated with YouTube"
        )

    except Exception as e:

        print(
            f"ERROR: Could not authenticate with YouTube: {e}"
        )

        return []

    # --------------------------------------------------------
    # Get/create station playlist
    # --------------------------------------------------------

    try:

        playlist_id = get_or_create_playlist(
            youtube,
            station_name
        )

        print(
            f"YouTube playlist ID: {playlist_id}"
        )

        # Get videos already in the playlist.
        youtube_video_ids = get_playlist_video_ids(
            youtube,
            playlist_id
        )

        print(
            f"YouTube playlist currently contains "
            f"{len(youtube_video_ids)} videos"
        )

    except Exception as e:

        print(
            f"ERROR: Could not access/create YouTube playlist "
            f"for {station_name}: {e}"
        )

        return []

    # --------------------------------------------------------
    # Scrape station
    # --------------------------------------------------------

    try:

        songs = scrape_playlist(url)

    except Exception as e:

        print(
            f"Failed to scrape {station_name}: {e}"
        )

        return []

    print(
        f"Scraped {len(songs)} tracks from {station_name}"
    )

    enriched = []

    # --------------------------------------------------------
    # Process songs
    # --------------------------------------------------------

    for idx, song in enumerate(
        songs,
        start=1
    ):

        artist = song["artist"]
        title = song["title"]

        print(
            f"[{idx}/{len(songs)}] "
            f"({station_name}) "
            f"{artist} - {title}"
        )

        # ----------------------------------------------------
        # Check CSV
        # ----------------------------------------------------

        csv_key = (
            f"{artist}|{title}"
        ).lower().strip()

        csv_path = get_csv_path(
            station_name
        )

        existing_keys = load_existing_keys(
            csv_path
        )

        already_in_csv = (
            csv_key in existing_keys
        )

        if already_in_csv:

            print(
                " -> Already exists in CSV"
            )

            # We don't need to process old tracks again.
            continue

        # ----------------------------------------------------
        # Deezer lookup
        # ----------------------------------------------------

        print(
            f" -> Searching Deezer: "
            f"{artist} - {title}"
        )

        deezer_info = search_deezer_track(
            artist,
            title
        )

        if deezer_info is None:

            print(
                " -> No Deezer match found"
            )

            continue

        song_with_deezer = {
            **song,
            "deezer_id": deezer_info["id"],
            "deezer_link": deezer_info["link"],
            "deezer_title": deezer_info["title"],
            "deezer_artist": deezer_info["artist"],
            "genre": deezer_info.get(
                "genre",
                "Unknown"
            ),
        }

        enriched.append(
            song_with_deezer
        )

        # ----------------------------------------------------
        # Add to CSV
        # ----------------------------------------------------

        added_to_csv = append_track_to_csv(
            station_name,
            song_with_deezer
        )

        if added_to_csv:

            print(
                f" -> Added to CSV: "
                f"{artist} - {title}"
            )

        # ----------------------------------------------------
        # Search YouTube
        # ----------------------------------------------------

        video_id = search_youtube_video(
            youtube,
            deezer_info["artist"],
            deezer_info["title"]
        )

        if video_id is None:

            print(
                " -> Could not find song on YouTube"
            )

            continue

        # ----------------------------------------------------
        # Check whether YouTube video is already in playlist
        # ----------------------------------------------------

        if video_id in youtube_video_ids:

            print(
                " -> Video is already in YouTube playlist"
            )

            continue

        # ----------------------------------------------------
        # Add to YouTube playlist
        # ----------------------------------------------------

        try:

            add_video_to_playlist(
                youtube,
                playlist_id,
                video_id
            )

            youtube_video_ids.add(
                video_id
            )

        except Exception as e:

            print(
                f" -> ERROR adding video to playlist: {e}"
            )

        sleep(0.3)

    # --------------------------------------------------------
    # Summary
    # --------------------------------------------------------

    print(
        f"\nSuccessfully matched "
        f"{len(enriched)} new tracks on Deezer "
        f"for {station_name}"
    )

    for track in enriched[:10]:

        print(
            f"{track['time']} - "
            f"{track['artist']} - "
            f"{track['title']} "
            f"({track.get('genre', 'Unknown')}) "
            f"-> {track['deezer_link']}"
        )

    with open(
        log_path,
        "a",
        encoding="utf-8"
    ) as log:

        log.write(
            f"Script finished (daily) for "
            f"{station_name}. "
            f"Matched {len(enriched)} tracks.\n"
        )

    return enriched


# ============================================================
# MAIN
# ============================================================

def run_daily():
    """
    Loop through every station in STATIONS
    and process each one separately.
    """

    for station_name, url in STATIONS.items():

        process_station(
            station_name,
            url
        )


if __name__ == "__main__":

    # Optionally run a single station:
    # python main.py bbc6

    if (
        len(sys.argv) > 1
        and sys.argv[1] in STATIONS
    ):

        process_station(
            sys.argv[1],
            STATIONS[sys.argv[1]]
        )

    else:

        run_daily()
