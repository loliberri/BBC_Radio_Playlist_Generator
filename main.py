# ============================================================

def get_or_create_playlist(youtube, station_name):
    """
    Find a YouTube playlist matching the station name.
    If it doesn't exist, create it.
    """

    playlist_title = station_name

    print(f"Checking YouTube playlist: {playlist_title}")

    # Get all playlists belonging to the authenticated account.
    request = youtube.playlists().list(
        part="snippet",
        mine=True,
        maxResults=50
    )

    while request:
        response = request.execute()

        for playlist in response.get("items", []):
            title = playlist["snippet"]["title"]

            if title.lower() == playlist_title.lower():
                playlist_id = playlist["id"]

                print(
                    f" -> Found existing YouTube playlist: "
                    f"{title} ({playlist_id})"
                )

                return playlist_id

        request = youtube.playlists().list_next(
            request,
            response
        )

    # Playlist doesn't exist, so create it.
    print(f" -> Creating YouTube playlist: {playlist_title}")

    playlist_body = {
        "snippet": {
            "title": playlist_title,
            "description": (
                f"Songs played on {station_name}, "
                "automatically generated by the radio scraper."
            )
        },
        "status": {
            "privacyStatus": "public"
        }
    }

    response = youtube.playlists().insert(
        part="snippet,status",
        body=playlist_body
    ).execute()

    playlist_id = response["id"]

    print(
        f" -> Created YouTube playlist: "
        f"{playlist_title} ({playlist_id})"
    )

    return playlist_id


def get_playlist_video_ids(youtube, playlist_id):
    """
    Get the YouTube video IDs already contained in a playlist.
    """

    video_ids = set()

    request = youtube.playlistItems().list(
        part="contentDetails",
        playlistId=playlist_id,
        maxResults=50
    )

    while request:
        response = request.execute()

        for item in response.get("items", []):
            video_id = item["contentDetails"]["videoId"]
            video_ids.add(video_id)

        request = youtube.playlistItems().list_next(
            request,
            response
        )

    return video_ids


def search_youtube_video(youtube, artist, title):
    """
    Search YouTube for a song and return the first video ID found.
    """

    query = f"{artist} {title}"

    print(f"    Searching YouTube: {query}")

    response = youtube.search().list(
        part="snippet",
        q=query,
        type="video",
        videoCategoryId="10",
        maxResults=1
    ).execute()

    items = response.get("items", [])

    if not items:
        print("    -> No YouTube result found")
        return None

    video_id = items[0]["id"]["videoId"]

    video_title = items[0]["snippet"]["title"]

    print(
        f"    -> YouTube result: {video_title} "
        f"(https://www.youtube.com/watch?v={video_id})"
    )

    return video_id


def add_video_to_playlist(youtube, playlist_id, video_id):
    """
    Add a YouTube video to a playlist.
    """

    body = {
        "snippet": {
            "playlistId": playlist_id,
            "resourceId": {
                "kind": "youtube#video",
                "videoId": video_id
            }
        }
    }

    youtube.playlistItems().insert(
        part="snippet",
        body=body
    ).execute()

    print(f"    -> Added video to playlist")


