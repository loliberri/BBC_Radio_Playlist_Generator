OUTPUT_DIR = os.path.join(
    os.path.dirname(__file__),
    "output"
)

FIELDNAMES = [
    "date",
    "time",
    "artist",
    "title",
    "genre",
    "deezer_link"
]


def get_csv_path(station_name):
    """Build the CSV file path for a given station."""

    os.makedirs(OUTPUT_DIR, exist_ok=True)

    return os.path.join(
        OUTPUT_DIR,
        f"{station_name}.csv"
    )


def load_existing_keys(path):
    """Read existing rows from a station's CSV to avoid duplicates."""

    existing_keys = set()

    if not os.path.exists(path):
        return existing_keys

    with open(
        path,
        "r",
        encoding="utf-8",
        newline=""
    ) as f:

        reader = csv.DictReader(f)

        for row in reader:

            key = (
                f"{row.get('artist', '')}|"
                f"{row.get('title', '')}"
            ).lower().strip()

            existing_keys.add(key)

    return existing_keys


def append_track_to_csv(station_name, track):
    """
    Append a single track row to that station's CSV.

    Returns True if the track was newly added.
    Returns False if it already existed.
    """

    path = get_csv_path(station_name)

    key = (
        f"{track['artist']}|"
        f"{track['title']}"
    ).lower().strip()

    existing_keys = load_existing_keys(path)

    if key in existing_keys:
        return False

    file_exists = os.path.exists(path)

    with open(
        path,
        "a",
        encoding="utf-8",
        newline=""
    ) as f:

        writer = csv.DictWriter(
            f,
            fieldnames=FIELDNAMES
        )

        if not file_exists:
            writer.writeheader()

        writer.writerow({
            "date": date.today().isoformat(),
            "time": track.get("time", ""),
            "artist": track.get("artist", ""),
            "title": track.get("title", ""),
            "genre": track.get("genre", "Unknown"),
            "deezer_link": track.get("deezer_link", ""),
        })

    return True


